#!/usr/bin/env bash
# Adds the private MyScript SDK, recognition assets and certificate to Notes
# in this build tree only. See myscript/README.md.
set -euo pipefail

src=${1:?usage: enable-myscript.sh <private folder>}
here=$(cd "$(dirname "$0")/.." && pwd)
dest=$here/myscript/private

test -f "$src/MyCertificate.java"
aar=$(ls "$src"/iink-*.aar | tail -n 1)
rm -rf "$dest"
mkdir -p "$dest/src/com/myscript/certificate" "$dest/assets"
cp "$src/MyCertificate.java" "$dest/src/com/myscript/certificate/"
cp "$aar" "$dest/iink.aar"
for zip in "$src"/myscript-iink-recognition-*.zip; do
    unzip -q -o "$zip" 'recognition-assets/*' -d "$dest/assets"
done

cat > "$here/myscript/Android.bp" <<'BP'
// Generated by tools/enable-myscript.sh: private, do not commit.
android_library_import {
    name: "PianoNotesIink",
    aars: ["private/iink.aar"],
    sdk_version: "current",
    min_sdk_version: "29",
    extract_jni: true,
}

android_library {
    name: "PianoNotesMyScript",
    manifest: "AndroidManifest.xml",
    srcs: ["private/src/**/*.java"],
    asset_dirs: ["private/assets"],
    static_libs: ["PianoNotesIink"],
    sdk_version: "current",
    min_sdk_version: "29",
}
BP
git -C "$here" update-index --skip-worktree myscript/Android.bp
echo "MyScript enabled for Notes in $here"
